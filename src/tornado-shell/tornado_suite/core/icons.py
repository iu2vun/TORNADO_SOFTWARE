@lru_cache(maxsize=2048)
def _pixmap(name: str, color: str, size: int) -> QPixmap:
    dpr = 2
    pm = QPixmap(size * dpr, size * dpr)
    pm.setDevicePixelRatio(dpr)
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    p.setRenderHint(QPainter.RenderHint.TextAntialiasing)
    k = size / 24.0
    col = QColor(color)
    pen = QPen(col, max(1.4, size / 14.0), Qt.PenStyle.SolidLine, Qt.PenCapStyle.RoundCap, Qt.PenJoinStyle.RoundJoin)
    p.setPen(pen)
    p.setBrush(Qt.BrushStyle.NoBrush)
    for op in ICONS.get(name, [("r", 4, 4, 16, 16), ("t", 8.5, 17, "?", 11)]):
        k0 = op[0]
        if k0 in ("l", "p"):
            poly = QPolygonF([QPointF(x * k, y * k) for x, y in op[1]])
            if k0 == "p":
                p.setBrush(col)
                p.drawPolygon(poly)
                p.setBrush(Qt.BrushStyle.NoBrush)
            else:
                p.drawPolyline(poly)
        elif k0 in ("r", "R"):
            r = QRectF(op[1] * k, op[2] * k, op[3] * k, op[4] * k)
            if k0 == "R":
                p.setBrush(col)
                p.setPen(Qt.PenStyle.NoPen)
                p.drawRect(r)
                p.setPen(pen)
                p.setBrush(Qt.BrushStyle.NoBrush)
            else:
                p.drawRoundedRect(r, 1.5 * k, 1.5 * k)
        elif k0 in ("e", "E"):
            cx, cy, rx, ry = (v * k for v in op[1:5])
            if k0 == "E":
                p.setBrush(col)
                p.setPen(Qt.PenStyle.NoPen)
            p.drawEllipse(QPointF(cx, cy), rx, ry)
            p.setPen(pen)
            p.setBrush(Qt.BrushStyle.NoBrush)
        elif k0 == "a":
            r = QRectF(op[1] * k, op[2] * k, op[3] * k, op[4] * k)
            p.drawArc(r, int(op[5] * 16), int(op[6] * 16))
        elif k0 == "t":
            f = QFont("Segoe UI")
            f.setBold(True)
            f.setPixelSize(max(6, int(op[4] * k)))
            p.setFont(f)
            p.drawText(QPointF(op[1] * k, op[2] * k), op[3])
    p.end()
    return pm


def icon(name: str, color: str | None = None, size: int = 24) -> QIcon:
    """QIcon con stati normale (testo), attivo (accento) e disabilitato."""
    ic = QIcon()
    base = color or P.text
    ic.addPixmap(_pixmap(name, base, size), QIcon.Mode.Normal)
    ic.addPixmap(_pixmap(name, P.accent, size), QIcon.Mode.Active)
    ic.addPixmap(_pixmap(name, P.accent, size), QIcon.Mode.Selected)
    ic.addPixmap(_pixmap(name, P.text_dim, size), QIcon.Mode.Disabled)
    return ic


def accent_icon(name: str, size: int = 24) -> QIcon:
    return icon(name, P.accent, size)


def pixmap(name: str, color: str | None = None, size: int = 24) -> QPixmap:
    return _pixmap(name, color or P.text, size)
